"""Independent fixture for the v4 hybrid USB channel key schedule (CableSession.establish).

Uses Python `cryptography`, not the app's code: ECDH P-256, HKDF-SHA256 extract over
ECDH secret || post-quantum secret, single-block expand per direction, AES-256-GCM frame.
The ML-KEM part enters as a fixed 64-byte input; ML-KEM itself is Bouncy Castle's FIPS 203
implementation and is exercised by PostQuantumTest. TEST keys only.
Run: python3 scripts/cable_vectors.py [--check]
"""
import base64, hashlib, hmac, struct, sys
from pathlib import Path
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = Path(__file__).resolve().parent.parent
V3 = ROOT / "test-vectors" / "cable-v3.properties"
OUT = ROOT / "test-vectors" / "cable-v4.properties"

def load(path):
    return dict(line.split("=", 1) for line in path.read_text().splitlines() if line and not line.startswith("#"))

def build():
    v = load(V3)
    b = lambda name: base64.b64decode(v[name])
    private = serialization.load_der_private_key(b("privateA"), None)
    peer = serialization.load_der_public_key(b("publicB"))
    shared = private.exchange(ec.ECDH(), peer)
    transcript, plaintext = b("transcript"), b("plaintext")
    post_quantum = bytes(range(64, 128))
    prk = hmac.new(transcript, shared + post_quantum, hashlib.sha256).digest()
    key = hmac.new(prk, b"Field hybrid USB v4 ECDH+ML-KEM-768 / A to B\x01", hashlib.sha256).digest()
    sequence = 0
    nonce = b"\0\0\0\0" + struct.pack(">q", sequence)
    aad = transcript + b"\x00" + struct.pack(">q", sequence)
    encrypted = AESGCM(key).encrypt(nonce, plaintext, aad)
    wire = struct.pack(">i", len(encrypted)) + struct.pack(">q", sequence) + encrypted
    e = lambda data: base64.b64encode(data).decode()
    return ("# Independent Python cryptography fixture for the v4 hybrid USB channel. Public TEST keys only.\n"
            "# Generated by scripts/cable_vectors.py from cable-v3 inputs plus a fixed post-quantum secret.\n"
            f"privateA={v['privateA']}\npublicA={v['publicA']}\npublicB={v['publicB']}\n"
            f"transcript={v['transcript']}\npostQuantum={e(post_quantum)}\nplaintext={e(plaintext)}\nwire={e(wire)}\n")

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else "cable-v4.properties is out of date")
    OUT.write_text(text)
